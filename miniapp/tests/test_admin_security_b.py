def test_an_old_lighter_hash_is_padded_to_the_current_work(monkeypatch):
    monkeypatch.setattr(accounts_module, "SCRYPT_P", 5)
    calls: list[int] = []
    real = hashlib.scrypt

    def spy(*args, **kwargs):
        calls.append(kwargs["p"])
        return real(*args, **kwargs)

    monkeypatch.setattr(accounts_module.hashlib, "scrypt", spy)
    salt = secrets.token_bytes(16)
    old = f"scrypt${2**14}$8$1${salt.hex()}${real(b'x', salt=salt, n=2**14, r=8, p=1, dklen=32).hex()}"
    assert not verify_password("wrong", old)
    assert sum(calls) == 5  # 1 for the hash itself + 4 of padding = the same work as an unknown e-mail
    calls.clear()
    verify_password("wrong", None)
    assert sum(calls) == 5


def test_schedule_is_refused_if_the_reviewed_recipients_changed(env):
    config, clock, client, accounts, secrets_ = env
    csrf = login(client, clock, secrets_, "admin@x.test")
    bid = post(client, "/api/admin/broadcasts", csrf, {"name": "VIP", "body": "Текст", "rules": {"tag_has": "VIP"}}).json()["id"]
    post(client, f"/api/admin/users/{U1}/tags", csrf, {"tag": "VIP"})
    shown = reviewed(client, bid)  # the admin sees U1 as the only recipient
    # Meanwhile (a session without the 2FA device): U1 out, another user in — the count stays 1.
    post(client, f"/api/admin/users/{U1}/tags/remove", csrf, {"tag": "VIP"})
    post(client, f"/api/admin/users/{U1 + 37}/tags", csrf, {"tag": "VIP"})
    body = {"reason": "план", "idempotencyKey": "sched-aud-1", "at": int(clock()) + 3600}
    swapped = post(client, f"/api/admin/broadcasts/{bid}/schedule", csrf,
                   {**body, **shown, "code": fresh(secrets_, clock, "admin@x.test")})
    assert (swapped.status_code, swapped.json()["error"]) == (409, "audience_changed")
    assert post(client, f"/api/admin/broadcasts/{bid}/schedule", csrf, {**body, "digest": shown["digest"],
                "code": fresh(secrets_, clock, "admin@x.test")}).json()["error"] == "audience_changed"  # none sent
    ok = post(client, f"/api/admin/broadcasts/{bid}/schedule", csrf,
              {**body, **reviewed(client, bid), "code": fresh(secrets_, clock, "admin@x.test")})
    assert ok.status_code == 200 and ok.json()["after"]["recipients"] == 1
