def _second_client(env) -> TestClient:
    return TestClient(env[2].app, base_url=ORIGIN)


def _hash(accounts, email: str) -> str:
    with sqlite3.connect(accounts.path) as conn:
        return conn.execute("SELECT password_hash FROM admin_users WHERE email = ?", (email,)).fetchone()[0]


def test_password_change_needs_current_password_and_code_and_ends_other_sessions(env):
    config, clock, client, accounts, secrets_ = env
    other = _second_client(env)
    login(other, clock, secrets_, "admin@x.test")
    csrf = login(client, clock, secrets_, "admin@x.test")
    url = "/api/admin/auth/password"
    wrong = post(client, url, csrf, {"current": "nope", "new": "a-new-long-password", "code": fresh(secrets_, clock, "admin@x.test")})
    assert (wrong.status_code, wrong.json()["error"]) == (403, "invalid_password")
    assert any(e["action"] == "auth.step_up_failed" for e in accounts.events())  # counted toward the lock
    assert post(client, url, csrf, {"current": "pw-admin", "new": "short", "code": fresh(secrets_, clock, "admin@x.test")}
                ).json()["error"] == "weak_password"
    assert post(client, url, csrf, {"current": "pw-admin", "new": "a-new-long-password", "code": "000000"}
                ).json()["error"] == "invalid_code"
    ok = post(client, url, csrf, {"current": "pw-admin", "new": "a-new-long-password", "code": fresh(secrets_, clock, "admin@x.test")})
    assert ok.status_code == 200 and ok.json()["revokedSessions"] == 1
    assert client.get("/api/admin/auth/me").status_code == 200  # this session stays
    assert other.get("/api/admin/auth/me").status_code == 401  # the other one ended
    assert verify_password("a-new-long-password", _hash(accounts, "admin@x.test"))
    assert client.post("/api/admin/auth/login", json={"email": "admin@x.test", "password": "pw-admin"},
                       headers=HDR).status_code == 401
    assert "a-new-long-password" not in str(accounts.events())


