def test_schedule_is_refused_if_the_draft_changed_after_review(env):
    config, clock, client, accounts, secrets_ = env
    csrf = login(client, clock, secrets_, "admin@x.test")
    saved = post(client, "/api/admin/broadcasts", csrf, {"name": "Тур", "body": "Текст"}).json()
    bid = saved["id"]
    assert saved["digest"] == digest_of(client, bid)
    seen = saved["digest"]
    post(client, f"/api/admin/broadcasts", csrf, {"id": bid, "name": "Тур", "body": "Другой текст"})  # edited meanwhile
    at = int(clock()) + 3600
    body = {"reason": "план", "idempotencyKey": "sched-dig-1", "at": at}
    stale = post(client, f"/api/admin/broadcasts/{bid}/schedule", csrf, {**body, "digest": seen,
                                                                         "code": fresh(secrets_, clock, "admin@x.test")})
    assert (stale.status_code, stale.json()["error"]) == (409, "broadcast_changed")
    assert post(client, f"/api/admin/broadcasts/{bid}/schedule", csrf, {**body, "code": fresh(secrets_, clock, "admin@x.test")}
                ).json()["error"] == "broadcast_changed"  # no digest at all (an older panel)
    ok = post(client, f"/api/admin/broadcasts/{bid}/schedule", csrf, {**body, **reviewed(client, bid),
                                                                      "code": fresh(secrets_, clock, "admin@x.test")})
    assert ok.status_code == 200


def test_direct_messages_are_capped_per_admin(env):
    config, clock, client, accounts, secrets_ = env
    csrf = login(client, clock, secrets_, "admin@x.test")
    for i in range(MESSAGES_PER_HOUR):
        assert post(client, f"/api/admin/users/{U1}/messages", csrf,
                    {"body": f"msg {i}", "idempotencyKey": f"msg-key-{i:04d}"}).status_code == 200
    over = post(client, f"/api/admin/users/{U1}/messages", csrf, {"body": "one more", "idempotencyKey": "msg-key-over"})
    assert (over.status_code, over.json()["error"]) == (429, "message_rate_limited")
    # A retry of an already queued message is not a new one.
    assert post(client, f"/api/admin/users/{U1}/messages", csrf,
                {"body": "msg 0", "idempotencyKey": "msg-key-0000"}).status_code == 200
    clock.t += 3601
    assert post(client, f"/api/admin/users/{U1}/messages", csrf,
                {"body": "next hour", "idempotencyKey": "msg-key-next"}).status_code == 200


