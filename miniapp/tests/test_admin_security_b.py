def test_owner_resets_a_colleague_who_then_sets_new_credentials(env):
    config, clock, client, accounts, secrets_ = env
    victim = _second_client(env)
    login(victim, clock, secrets_, "admin@x.test")
    admin_csrf = victim.get("/api/admin/auth/me").json()["csrf"]
    admin_id = victim.get("/api/admin/auth/me").json()["admin"]["id"]
    assert post(victim, f"/api/admin/admins/{admin_id}/reset", admin_csrf,
                {"reason": "потерял телефон", "idempotencyKey": "reset-key-0", "code": fresh(secrets_, clock, "admin@x.test")}
                ).status_code == 403  # owner only
    csrf = login(client, clock, secrets_, "owner@x.test")
    owner_id = client.get("/api/admin/auth/me").json()["admin"]["id"]
    body = {"reason": "потерял телефон", "idempotencyKey": "reset-key-1"}
    assert post(client, f"/api/admin/admins/{owner_id}/reset", csrf, {**body, "code": fresh(secrets_, clock)}
                ).json()["error"] == "use_password_change"
    r = post(client, f"/api/admin/admins/{admin_id}/reset", csrf, {**body, "idempotencyKey": "reset-key-2",
                                                                   "code": fresh(secrets_, clock)}).json()
    token = r["inviteToken"]
    assert victim.get("/api/admin/auth/me").status_code == 401  # every session of the account ended
    row = next(a for a in accounts.admins() if a["id"] == admin_id)
    assert row["state"] == "invited" and row["twoFactor"] is False and row["role"] == "admin"
    assert client.post("/api/admin/auth/login", json={"email": "admin@x.test", "password": "pw-admin"},
                       headers=HDR).status_code == 401  # the old password is gone
    fresh_client = _second_client(env)
    info = fresh_client.post("/api/admin/auth/invite", json={"token": token}, headers=HDR).json()
    assert info["secret"] != secrets_["admin@x.test"]  # a new 2FA secret
    clock.t += 30
    good = totp.code_at(info["secret"], int(clock() // 30))
    assert fresh_client.post("/api/admin/auth/invite/accept", json={"token": token, "password": "brand-new-password",
                                                                   "code": good}, headers=HDR).json() == {"ok": True}
    assert next(a for a in accounts.admins() if a["id"] == admin_id)["state"] == "active"
    assert token not in str(accounts.events())


def test_locks_grow_and_failures_are_journalled(env):
    config, clock, client, accounts, secrets_ = env

    def fail_five() -> int:
        for _ in range(MAX_FAILURES):
            client.post("/api/admin/auth/login", json={"email": "analyst@x.test", "password": "pw-analyst"}, headers=HDR)
            client.post("/api/admin/auth/totp", json={"code": "000000"}, headers=HDR)
        with sqlite3.connect(accounts.path) as conn:
            return conn.execute("SELECT locked_until FROM admin_users WHERE email = 'analyst@x.test'").fetchone()[0]

    until = fail_five()
    assert until - int(clock()) == LOCK_S
    assert sum(e["action"] == "auth.totp_failed" and e["result"] == "failed" for e in accounts.events()) == MAX_FAILURES
    clock.t = until + 1
    assert fail_five() - int(clock()) == 2 * LOCK_S  # the second lock within a day lasts twice as long
    assert accounts.cli_unlock("analyst@x.test", int(clock()))
    login(client, clock, secrets_, "analyst@x.test")  # unlocked from the server shell


def test_old_scrypt_hashes_are_redone_at_login(env, monkeypatch):
    config, clock, client, accounts, secrets_ = env
    monkeypatch.setattr(accounts_module, "SCRYPT_P", 5)  # the production parameters (conftest lightens them)
    salt = secrets.token_bytes(16)
    old = f"scrypt${2**14}$8$1${salt.hex()}${hashlib.scrypt(b'pw-analyst', salt=salt, n=2**14, r=8, p=1, dklen=32).hex()}"
    with sqlite3.connect(accounts.path) as conn:
        conn.execute("UPDATE admin_users SET password_hash = ? WHERE email = 'analyst@x.test'", (old,))
    assert needs_rehash(old)
    login(client, clock, secrets_, "analyst@x.test")
    new = _hash(accounts, "analyst@x.test")
    assert new != old and not needs_rehash(new) and new.split("$")[1:4] == [str(SCRYPT_N), "8", "5"]
    assert verify_password("pw-analyst", new)


